def grad(y, x):
    return torch.autograd.grad(
        y, x,
        grad_outputs=torch.ones_like(y),
        create_graph=True,
        retain_graph=True
    )[0]


def positive_params():
    E0 = torch.nn.functional.softplus(E0_raw) + 1e-12
    eta = torch.nn.functional.softplus(eta_raw) + 1e-12
    kx = torch.nn.functional.softplus(kx_raw) + 1e-12
    kphi = torch.nn.functional.softplus(kphi_raw) + 1e-12
