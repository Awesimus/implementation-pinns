def load_experimental_frf(path, x_meas):
    ext = os.path.splitext(path)[1].lower()

    # expanded key candidates
    freq_candidates = ["freq", "f", "frequency", "f_hz", "freq_s1", "freq_s2"]
    frf_candidates  = ["frf", "V", "velocity", "response", "H", "s1_fft", "s2_fft"]
    real_candidates = ["real", "V_real", "vr", "Re"]
    imag_candidates = ["imag", "V_imag", "vi", "Im"]

    if ext == ".npz":
        data = np.load(path, allow_pickle=True)
        print("NPZ keys:", list(data.keys()))

        f_key = _pick_first_key(data, freq_candidates)
        frf_key = _pick_first_key(data, frf_candidates)

        if f_key is not None and frf_key is not None:
            f_hz = np.asarray(data[f_key]).reshape(-1).astype(float)
            V = np.asarray(data[frf_key]).reshape(-1)

            # if FRF is not complex, try to interpret shape
            if not np.iscomplexobj(V):
                raise ValueError(
                    f"Found FRF key '{frf_key}', but array is not complex. "
                    "Please inspect its structure."
                )

        else:
            real_key = _pick_first_key(data, real_candidates)
            imag_key = _pick_first_key(data, imag_candidates)

            if f_key is None or real_key is None or imag_key is None:
                raise ValueError(
                    f"Could not parse NPZ structure. Available keys: {list(data.keys())}"
                )

            f_hz = np.asarray(data[f_key]).reshape(-1).astype(float)
            V = np.asarray(data[real_key]).reshape(-1) + 1j * np.asarray(data[imag_key]).reshape(-1)

    elif ext == ".npy":
        arr = np.load(path, allow_pickle=True)

        # dict saved inside .npy
        if hasattr(arr, "item"):
            try:
                data = arr.item()
            except Exception:
                data = None
        else:
            data = None

        if isinstance(data, dict):
            print("NPY dict keys:", list(data.keys()))

            f_key = _pick_first_key(data, freq_candidates)
            frf_key = _pick_first_key(data, frf_candidates)

            if f_key is not None and frf_key is not None:
                f_hz = np.asarray(data[f_key]).reshape(-1).astype(float)
                V = np.asarray(data[frf_key]).reshape(-1)

                if not np.iscomplexobj(V):
                    raise ValueError(
                        f"Found FRF key '{frf_key}', but array is not complex. "
                        "Please inspect its structure."
                    )

            else:
                real_key = _pick_first_key(data, real_candidates)
                imag_key = _pick_first_key(data, imag_candidates)

                if f_key is None or real_key is None or imag_key is None:
                    raise ValueError(
                        f"Could not parse NPY dict structure. Available keys: {list(data.keys())}"
                    )

                f_hz = np.asarray(data[f_key]).reshape(-1).astype(float)
                V = np.asarray(data[real_key]).reshape(-1) + 1j * np.asarray(data[imag_key]).reshape(-1)

        else:
            raise ValueError(
                "Plain .npy array without frequency information is ambiguous. "
                "Please provide .npz or .npy dict with frequency + FRF."
            )

    else:
        raise ValueError("Only .npy and .npz are supported in this notebook.")

    # Basic checks
    f_hz = np.asarray(f_hz).reshape(-1)
    V = np.asarray(V).reshape(-1)

    if len(f_hz) != len(V):
        raise ValueError(
            f"Frequency and FRF lengths do not match: len(f_hz)={len(f_hz)}, len(V)={len(V)}"
        )

    # finite values only
    mask = np.isfinite(f_hz) & np.isfinite(V.real) & np.isfinite(V.imag)
    f_hz = f_hz[mask]
    V = V[mask]

    # non-negative frequencies only
    mask = f_hz >= 0.0
    f_hz = f_hz[mask]
    V = V[mask]

    # sort
    order = np.argsort(f_hz)
    f_hz = f_hz[order]
    V = V[order]

    # remove duplicate frequencies by averaging complex values
    df = pd.DataFrame({
        "f_hz": f_hz,
        "V_real": V.real,
        "V_imag": V.imag
    })
    df = df.groupby("f_hz", as_index=False).mean()

    f_hz = df["f_hz"].to_numpy()
    V = df["V_real"].to_numpy() + 1j * df["V_imag"].to_numpy()

    x = np.full_like(f_hz, fill_value=x_meas, dtype=float)

    return f_hz, x, V

