def normalize_x(x):
    # map [0, L] -> [-1, 1]
    return 2.0 * x / L - 1.0


def normalize_omega(omega):
    # map [omega_min, omega_max] -> [-1, 1]
    return 2.0 * (omega - omega_min) / (omega_max - omega_min) - 1.0

"""PINN model"""

class PINN(nn.Module):
    """
    Input:  (x, omega)
    Output: (W_real, W_imag)
    """
    def __init__(self, layers=[2, 128, 128, 128, 128, 2]):
        super().__init__()
        self.layers = nn.ModuleList()
        for i in range(len(layers) - 1):
            self.layers.append(nn.Linear(layers[i], layers[i + 1]))
        self.act = nn.Tanh()

    def forward(self, x, omega):
        x_n = normalize_x(x)
        w_n = normalize_omega(omega)
        z = torch.cat([x_n, w_n], dim=1)

        for layer in self.layers[:-1]:
            z = self.act(layer(z))

        out = self.layers[-1](z)
        Wr = out[:, 0:1]
        Wi = out[:, 1:2]
        return Wr, Wi


