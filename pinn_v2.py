"""Loss function for pinn_v2
It matches the beam_theories_changes.py convention.
"""

# Fixed known geometry terms
A_t, I_t = area_and_inertia(width, height, bending_axis=bending_axis)
A_t = torch.tensor(A_t, dtype=torch.float32, device=device)
I_t = torch.tensor(I_t, dtype=torch.float32, device=device)
rho_t = torch.tensor(rho, dtype=torch.float32, device=device)
m_tip_t = torch.tensor(m_tip, dtype=torch.float32, device=device)


def pinn_v2_loss(
    pinn,
    x_col,
    omega_col,
    x_data,
    omega_data,
    Vr_data,
    Vi_data,
    w_pde=1.0,
    w_bc=10.0,
    w_data=1.0,
):
    E0, eta, kx, kphi, F = positive_params()

    # Complex modulus E = E0 * (1 + i eta)
    E_r = E0
    E_i = E0 * eta

    EI_r = E_r * I_t
    EI_i = E_i * I_t

    # ===================================
    # PDE residual
    # EI * W_xxxx - rho*A*omega^2 * W = 0
    # ===================================
    Wr, Wi = pinn(x_col, omega_col)

    Wr_x = grad(Wr, x_col)
    Wr_xx = grad(Wr_x, x_col)
    Wr_xxx = grad(Wr_xx, x_col)
    Wr_xxxx = grad(Wr_xxx, x_col)

    Wi_x = grad(Wi, x_col)
    Wi_xx = grad(Wi_x, x_col)
    Wi_xxx = grad(Wi_xx, x_col)
    Wi_xxxx = grad(Wi_xxx, x_col)

    omega2 = omega_col**2

    EI_W4_r = EI_r * Wr_xxxx - EI_i * Wi_xxxx
    EI_W4_i = EI_r * Wi_xxxx + EI_i * Wr_xxxx

    r_pde_r = EI_W4_r - rho_t * A_t * omega2 * Wr
    r_pde_i = EI_W4_i - rho_t * A_t * omega2 * Wi

    pde_loss = torch.mean(r_pde_r**2 + r_pde_i**2)

    # ===================================
    # Boundary conditions
    # Convention from beam_theories_changes active implementation:
    #
    # EI w''(0) + kphi w'(0) = 0
    # EI w'''(0) + kx  w(0)  = 0
    # w''(L) = 0
    # EI w'''(L) + m_tip*omega^2*w(L) + F = 0
    # ===================================
    omega_b = omega_col.detach()

    # x = 0
    x0 = torch.zeros_like(omega_b, requires_grad=True)
    Wr0, Wi0 = pinn(x0, omega_b)

    Wr0_x = grad(Wr0, x0)
    Wr0_xx = grad(Wr0_x, x0)
    Wr0_xxx = grad(Wr0_xx, x0)

    Wi0_x = grad(Wi0, x0)
    Wi0_xx = grad(Wi0_x, x0)
    Wi0_xxx = grad(Wi0_xx, x0)

    bc0_m_r = (EI_r * Wr0_xx - EI_i * Wi0_xx) + kphi * Wr0_x
    bc0_m_i = (EI_r * Wi0_xx + EI_i * Wr0_xx) + kphi * Wi0_x

    bc0_v_r = (EI_r * Wr0_xxx - EI_i * Wi0_xxx) + kx * Wr0
    bc0_v_i = (EI_r * Wi0_xxx + EI_i * Wr0_xxx) + kx * Wi0

    # x = L
    xL = torch.full_like(omega_b, fill_value=L, requires_grad=True)
    WrL, WiL = pinn(xL, omega_b)

    WrL_x = grad(WrL, xL)
    WrL_xx = grad(WrL_x, xL)
    WrL_xxx = grad(WrL_xx, xL)

    WiL_x = grad(WiL, xL)
    WiL_xx = grad(WiL_x, xL)
    WiL_xxx = grad(WiL_xx, xL)

    # w''(L) = 0
    bcL_m_r = WrL_xx
    bcL_m_i = WiL_xx

    # EI w'''(L) + m_tip*omega^2*w(L) + F = 0
    # F is taken as real scalar amplitude here
    bcL_v_r = (EI_r * WrL_xxx - EI_i * WiL_xxx) + m_tip_t * (omega_b**2) * WrL + F
    bcL_v_i = (EI_r * WiL_xxx + EI_i * WrL_xxx) + m_tip_t * (omega_b**2) * WiL

    bc_loss = torch.mean(
        bc0_m_r**2 + bc0_m_i**2 +
        bc0_v_r**2 + bc0_v_i**2 +
        bcL_m_r**2 + bcL_m_i**2 +
        bcL_v_r**2 + bcL_v_i**2
    )

    # ===================================
    # Data loss on velocity FRF
    # V = i * omega * W
    # => V_real = -omega * Wi
    # => V_imag =  omega * Wr
    # ===================================
    Wr_d, Wi_d = pinn(x_data, omega_data)

    Vp_r = -omega_data * Wi_d
    Vp_i =  omega_data * Wr_d

    data_loss = torch.mean((Vp_r - Vr_data)**2 + (Vp_i - Vi_data)**2)

    total_loss = w_pde * pde_loss + w_bc * bc_loss + w_data * data_loss

    logs = {
        "loss": total_loss.detach().item(),
        "pde": pde_loss.detach().item(),
        "bc": bc_loss.detach().item(),
        "data": data_loss.detach().item(),
        "E0": E0.detach().item(),
        "eta": eta.detach().item(),
        "kx": kx.detach().item(),
        "kphi": kphi.detach().item(),
        "F": F.detach().item(),
    }

    return total_loss, logs

"""Training loop"""

